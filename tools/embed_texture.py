#!/usr/bin/env python3
"""Embed a binary asset as a C++ byte array.

Usage:
    tools/embed_texture.py assets/earth_1024.jpg \
        src/render/EarthTextureData.hpp src/render/EarthTextureData.cpp

The generated files are committed so the binary stays self-contained and the
build does not need Python.
"""

from __future__ import annotations

import pathlib
import sys


def render_header(symbol: str) -> str:
    return f"""// Generated by tools/embed_texture.py. Do not edit by hand.
#pragma once

#include <cstddef>

namespace secgui {{

extern const unsigned char {symbol}[];
extern const std::size_t {symbol}Size;

}} // namespace secgui
"""


def render_source(symbol: str, source: pathlib.Path, data: bytes) -> str:
    lines = [
        "// Generated by tools/embed_texture.py. Do not edit by hand.",
        f'// Source: {source.as_posix()} ({len(data)} bytes)',
        '#include "render/EarthTextureData.hpp"',
        "",
        "namespace secgui {",
        "",
        f"const unsigned char {symbol}[] = {{",
    ]
    row: list[str] = []
    for index, value in enumerate(data):
        row.append(f"0x{value:02x},")
        if len(row) == 16:
            lines.append("\t" + " ".join(row))
            row = []
    if row:
        lines.append("\t" + " ".join(row))
    lines.extend([
        "};",
        "",
        f"const std::size_t {symbol}Size = sizeof({symbol});",
        "",
        "} // namespace secgui",
        "",
    ])
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    source = pathlib.Path(argv[1])
    header_path = pathlib.Path(argv[2])
    cpp_path = pathlib.Path(argv[3])
    data = source.read_bytes()
    symbol = "kEarthTextureJpeg"
    header_path.write_text(render_header(symbol))
    cpp_path.write_text(render_source(symbol, source, data))
    print(f"embedded {source} -> {header_path}, {cpp_path} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
